INSERT INTO `ticket_stock` (`travel_date`, `train_id`, `segment_index`, `seat_type`, `from_station_id`, `to_station_id`, `total_count`, `sold_count`, `remaining_count`)
SELECT x.travel_date, x.train_id, x.segment_index, x.seat_type,
       x.from_station_id, x.to_station_id, x.total_count,
       LEAST(x.total_count, MOD(x.train_id * 7 + x.segment_index * 3
                              + x.day_no + x.seat_type * 2, 19)) AS sold_count,
       x.total_count - LEAST(x.total_count,
           MOD(x.train_id * 7 + x.segment_index * 3
               + x.day_no + x.seat_type * 2, 19)) AS remaining_count
FROM (
    SELECT DATE_ADD(CURDATE(), INTERVAL (1 + days.day_no) DAY) AS travel_date,
           seg.train_id, seg.segment_index, seats.seat_type,
           seg.from_station_id, seg.to_station_id, days.day_no,
           CASE t.train_type
             WHEN 'G' THEN CASE seats.seat_type WHEN 1 THEN 20 WHEN 2 THEN 100 ELSE 600 END
             WHEN 'D' THEN CASE seats.seat_type WHEN 1 THEN 16 WHEN 2 THEN 80 ELSE 500 END
             WHEN 'K' THEN CASE seats.seat_type WHEN 1 THEN 8 WHEN 2 THEN 40 ELSE 300 END
             WHEN 'T' THEN CASE seats.seat_type WHEN 1 THEN 8 WHEN 2 THEN 48 ELSE 360 END
             ELSE CASE seats.seat_type WHEN 1 THEN 8 WHEN 2 THEN 48 ELSE 360 END
           END AS total_count
    FROM `train_segment` seg
    JOIN `train` t ON t.id = seg.train_id
    CROSS JOIN (
        SELECT 0 AS day_no
        UNION ALL SELECT 1 AS day_no
        UNION ALL SELECT 2 AS day_no
        UNION ALL SELECT 3 AS day_no
        UNION ALL SELECT 4 AS day_no
        UNION ALL SELECT 5 AS day_no
        UNION ALL SELECT 6 AS day_no
