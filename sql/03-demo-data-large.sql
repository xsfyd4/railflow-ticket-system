        UNION ALL SELECT 8 AS day_no
        UNION ALL SELECT 9 AS day_no
        UNION ALL SELECT 10 AS day_no
        UNION ALL SELECT 11 AS day_no
        UNION ALL SELECT 12 AS day_no
        UNION ALL SELECT 13 AS day_no
        UNION ALL SELECT 14 AS day_no
        UNION ALL SELECT 15 AS day_no
        UNION ALL SELECT 16 AS day_no
        UNION ALL SELECT 17 AS day_no
        UNION ALL SELECT 18 AS day_no
        UNION ALL SELECT 19 AS day_no
        UNION ALL SELECT 20 AS day_no
        UNION ALL SELECT 21 AS day_no
        UNION ALL SELECT 22 AS day_no
        UNION ALL SELECT 23 AS day_no
        UNION ALL SELECT 24 AS day_no
        UNION ALL SELECT 25 AS day_no
        UNION ALL SELECT 26 AS day_no
        UNION ALL SELECT 27 AS day_no
        UNION ALL SELECT 28 AS day_no
        UNION ALL SELECT 29 AS day_no
    ) days
    CROSS JOIN (
        SELECT 1 AS seat_type
        UNION ALL SELECT 2
